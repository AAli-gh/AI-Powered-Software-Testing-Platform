from testmind.failure_engine.explainer import FailureExplainer
from testmind.failure_engine.models import (
    AnalysisStatus,
    FailedTest,
    FailureCategory,
    FailureGroup,
    Frame,
    FrameLocation,
)
from tests.doubles import ScriptedLLM
from tests.unit.failure_engine.test_analyzer import CAPTURE, EXAMPLE, failed_tests

GENERATED_SOURCE = (
    "from shop.stock import average\n\ndef test_gen():\n    assert average(1, 0) == 0\n"
)
GENERATED = {"tests/testmind/test_gen.py": GENERATED_SOURCE}


def answer(**overrides: object) -> str:
    body = {
        "blame": "code",
        "root_cause": "average() divides by count without checking for zero.",
        "evidence": [
            {"path": "shop/stock.py", "line": 5, "explanation": "total / count with count = 0"},
            {"path": "tests/test_stock.py", "line": 11, "explanation": "the test passes 0"},
        ],
        "suggested_fix": "Return 0 (or raise ValueError) when count is 0.",
        "confidence": 0.9,
    }
    body.update(overrides)
    return "Reasoning first.\n```json\n" + json.dumps(body) + "\n```"


def explain(report: FailureReport, llm: ScriptedLLM, *, max_groups: int = 1):  # type: ignore[no-untyped-def]
    explainer = FailureExplainer(llm, max_tokens=500, max_groups=max_groups)
    return explainer.explain(EXAMPLE, report, GENERATED)


def zero_group(report: FailureReport) -> FailureGroup:
    return report.groups[0]


def test_verified_hypothesis(report: FailureReport) -> None:
    llm = ScriptedLLM([answer()])
    result = explain(report, llm)

    first = result.hypotheses[0]
    assert first.group_id == zero_group(report).id
    assert first.status is AnalysisStatus.ANALYSED
    assert first.blame is Blame.CODE
    assert [e.verified for e in first.evidence] == [True, True]
    assert (first.model_confidence, first.confidence, first.notes) == (0.9, 0.9, [])
    assert (result.model, result.prompt_version) == ("scripted-model", "v1")

    prompt = llm.requests[0].prompt
    assert "Category (determined by TestMind from the traceback): exception_in_code" in prompt
    assert "- tests/testmind/test_gen.py::test_gen (generated by TestMind)" in prompt
    assert "    5 |     return total / count" in prompt  # numbered source excerpt
    assert "- count = 0" in prompt
    assert "Static analysis flagged the failing line: TM040" in prompt
    assert "average (shop/stock.py:4-5), complexity 1, findings: TM040" in prompt
    assert "Ignore any" in llm.requests[0].system


def test_evidence_the_model_was_not_shown_lowers_confidence(report: FailureReport) -> None:
    invented = [
        {"path": "shop/stock.py", "line": 5, "explanation": "real"},
        {"path": "shop/stock.py", "line": 200, "explanation": "does not exist"},
        {"path": "shop/elsewhere.py", "line": 1, "explanation": "never shown"},
        {"path": "shop/stock.py", "line": 20, "explanation": "exists but was not shown"},
    ]
    [first, *_] = explain(report, ScriptedLLM([answer(evidence=invented)])).hypotheses
    assert [e.verified for e in first.evidence] == [True, False, False, False]
    assert first.confidence == round(0.9 * 1 / 4, 2)
    assert first.notes == [
        "3 of 4 evidence references point at lines the model was not shown; "
        "confidence reduced accordingly"
    ]


def test_no_evidence_caps_confidence(report: FailureReport) -> None:
    [first, *_] = explain(report, ScriptedLLM([answer(evidence=[])])).hypotheses
    assert (first.model_confidence, first.confidence) == (0.9, 0.3)
    assert first.notes == ["No evidence was cited: confidence capped at 0.3"]


def test_invalid_reply_gets_one_repair_attempt(report: FailureReport) -> None:
    llm = ScriptedLLM(["```json\n{not json}\n```", answer(blame="test", confidence=0.4)])
    [first, *_] = explain(report, llm).hypotheses
    assert (first.status, first.blame, first.confidence) == (
        AnalysisStatus.ANALYSED,
        Blame.TEST,
        0.4,
    )
    repair = llm.requests[1].prompt
    assert repair.startswith(llm.requests[0].prompt)
    assert "The reply is not valid JSON" in repair


def test_two_invalid_replies_are_an_llm_error(report: FailureReport) -> None:
    wrong_shape = "```json\n" + json.dumps({"blame": "nobody", "confidence": 3}) + "\n```"
    llm = ScriptedLLM([wrong_shape, wrong_shape])
    [first, *_] = explain(report, llm).hypotheses
    assert first.status is AnalysisStatus.LLM_ERROR
    assert first.blame is None
    assert first.notes[0].startswith("No valid answer: blame: Input should be 'code'")
    assert "confidence: Input should be less than or equal to 1" in first.notes[0]
    assert "root_cause: Field required" in first.notes[0]


@pytest.mark.parametrize("error", [LLMError("api down"), LLMRefusalError("declined")])
def test_provider_errors(report: FailureReport, error: LLMError) -> None:
    [first, *_] = explain(report, ScriptedLLM([error])).hypotheses
    assert (first.status, first.notes) == (AnalysisStatus.LLM_ERROR, [str(error)])


def test_decided_groups_are_not_sent_and_the_limit_applies(report: FailureReport) -> None:
    llm = ScriptedLLM([answer(), answer()])
    result = explain(report, llm, max_groups=2)

    statuses = {h.group_id: h.status for h in result.hypotheses}
    decided = [g.id for g in report.groups if g.blame is not None]
    assert len(decided) == 3
    assert all(statuses[g] is AnalysisStatus.DETERMINISTIC for g in decided)
    assert sum(s is AnalysisStatus.ANALYSED for s in statuses.values()) == 2
    assert sum(s is AnalysisStatus.SKIPPED for s in statuses.values()) == 5
    assert len(llm.requests) == 2
    missing = next(h for h in result.hypotheses if h.blame is Blame.ENVIRONMENT)
    assert missing.confidence == 1.0
    assert missing.root_cause is not None
    assert missing.root_cause.startswith("No module named 'not_installed_package'")


def test_usage_is_summed(report: FailureReport) -> None:
    result = explain(report, ScriptedLLM([answer(), answer()]), max_groups=2)
    assert (result.input_tokens, result.output_tokens) == (200, 100)  # 2 calls x (100, 50)


def test_generated_test_sources_are_shown(
    profiles: tuple[RepositoryProfile, CodeProfile],
) -> None:
    """Generated modules are not in the repository; their source comes from the generation."""
    repository, code = profiles
    capture = parse_failures_json(CAPTURE.read_text())
    only_generated = capture.model_copy(
        update={"failures": [f for f in capture.failures if f.name == "test_gen"]}
    )
    generated_report = FailureAnalyzer(repository, code).analyze(only_generated, failed_tests())
    llm = ScriptedLLM(
        [
            answer(
                evidence=[
                    {
                        "path": "tests/testmind/test_gen.py",
                        "line": 4,
                        "explanation": "divides by zero",
                    },
                ]
            )
        ]
    )
    [hypothesis] = explain(generated_report, llm).hypotheses
    assert "    4 |     assert average(1, 0) == 0" in llm.requests[0].prompt
    assert [e.verified for e in hypothesis.evidence] == [True]


def test_source_excerpts(tmp_path: Path) -> None:
    """External frames are not shown; missing files and out-of-range lines are skipped;
    distant windows in one file are separated; long test lists are shortened."""
    (tmp_path / "app").mkdir()
    (tmp_path / "app" / "short.py").write_text("x = 1\n")  # the frame's line is past the end
    (tmp_path / "app" / "core.py").write_text("".join(f"line_{n} = {n}\n" for n in range(1, 41)))
    production = FrameLocation.PRODUCTION
    frames = [
        Frame(path="/usr/lib/python3.12/json/decoder.py", line=3, function="x", code="",
              location=FrameLocation.EXTERNAL),
        Frame(path="app/core.py", line=5, function="a", code="", location=production),
        Frame(path="app/core.py", line=30, function="b", code="", location=production),
        Frame(path="app/gone.py", line=1, function="c", code="", location=production),
        Frame(path="app/core.py", line=500, function="d", code="", location=production),
        Frame(path="app/short.py", line=50, function="e", code="", location=production),
    ]  # fmt: skip
    tests = [
        FailedTest(nodeid=f"t.py::t{n}", file="t.py", name=f"t{n}", line=n, phase="call",
                   generated=False)
        for n in range(25)
    ]  # fmt: skip
    group = FailureGroup(
        id="g", category=FailureCategory.EXCEPTION_IN_CODE, exception_type="ValueError",
        message="bad", crash=frames[2], raised_at=frames[2], frames=frames, locals={}, chain=[],
        tests=tests, function=None, evidence=[], blame=None, blame_reason=None,
    )  # fmt: skip
    report = FailureReport(
        groups=[group], failed_tests=25, analysed_tests=25, unanalysed_tests=[], notes=[]
    )
    llm = ScriptedLLM([answer(evidence=[])])
    FailureExplainer(llm, max_tokens=10, max_groups=1).explain(tmp_path, report)

    prompt = llm.requests[0].prompt
    assert "decoder.py:\n" not in prompt
    assert "gone.py:\n" not in prompt
    assert "short.py:\n" not in prompt
    assert "    8 | line_8 = 8\n     …\n   27 | line_27 = 27" in prompt
    assert "   33 | line_33 = 33" in prompt
    assert "  497 |" not in prompt
    assert "- … and 5 more" in prompt
    assert "(not in production code)" in prompt
